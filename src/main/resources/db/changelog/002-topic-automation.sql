UPDATE ai_topics
SET dedupe_key = encode(digest(lower(regexp_replace(trim(title), '\s+', ' ', 'g')), 'sha256'), 'hex'),
    last_seen_at = created_at,
    updated_at = created_at
WHERE dedupe_key IS NULL;

-- Preserve existing duplicate rows without losing them. New discoveries use the
-- canonical title hash and will merge into the first row in each legacy group.
WITH duplicate_rows AS (
    SELECT id, row_number() OVER (PARTITION BY dedupe_key ORDER BY id) AS row_number
    FROM ai_topics
)
UPDATE ai_topics topic
SET dedupe_key = encode(digest(topic.dedupe_key || ':' || topic.id, 'sha256'), 'hex')
FROM duplicate_rows duplicate_row
WHERE topic.id = duplicate_row.id
  AND duplicate_row.row_number > 1;

