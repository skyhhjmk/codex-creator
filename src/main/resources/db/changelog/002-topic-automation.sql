CREATE TABLE topic_automation_settings (
    id BIGINT PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    interval_minutes INTEGER NOT NULL DEFAULT 360,
    max_seeds_per_run INTEGER NOT NULL DEFAULT 5,
    max_topics_per_run INTEGER NOT NULL DEFAULT 20,
    next_run_at TIMESTAMPTZ,
    last_run_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    last_error TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_topic_interval_minutes CHECK (interval_minutes BETWEEN 60 AND 1440),
    CONSTRAINT chk_topic_max_seeds CHECK (max_seeds_per_run BETWEEN 1 AND 20),
    CONSTRAINT chk_topic_max_topics CHECK (max_topics_per_run BETWEEN 1 AND 50)
);

